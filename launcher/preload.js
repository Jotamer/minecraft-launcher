const { contextBridge, ipcRenderer, webUtils } = require("electron");
const inv = (ch) => (a) => ipcRenderer.invoke(ch, a);
const on = (ch) => (cb) => ipcRenderer.on(ch, (_e, p) => cb(p));

contextBridge.exposeInMainWorld("L", {
  autoLogin: inv("auth:auto"),
  login: inv("auth:login"),
  logout: () => ipcRenderer.invoke("auth:logout"),
  users: inv("users"),
  accounts: inv("accounts:list"),
  switchAccount: inv("accounts:switch"),
  removeAccount: inv("accounts:remove"),
  openFolder: inv("instance:openFolder"),
  changelog: inv("instance:changelog"),
  serverChangelog: inv("changelog:get"),
  gameLog: inv("game:log"),
  openUrl: inv("app:openUrl"),
  instancesDir: inv("instances:get"),
  pickInstancesDir: inv("instances:pick"),
  setInstancesDir: inv("instances:set"),
  catalog: inv("catalog"),
  play: inv("play"),
  install: inv("instance:install"),
  banner: inv("instance:banner"),
  getSettings: inv("settings:get"),
  setSettings: inv("settings:set"),
  getGlobalSettings: () => ipcRenderer.invoke("globalSettings:get"),
  setGlobalSettings: inv("globalSettings:set"),
  openInstancesFolder: () => ipcRenderer.invoke("instances:open"),
  themeBoot: () => ipcRenderer.sendSync("theme:boot"),
  setTheme: inv("theme:set"),
  support: inv("support"),
  requestAccount: inv("request:account"),
  presence: () => ipcRenderer.invoke("presence"),
  pickAvatar: () => ipcRenderer.invoke("avatar:pick"),
  setAvatar: inv("avatar:set"),
  avatar: inv("avatar:get"),
  setAccountAvatar: inv("accounts:setAvatar"),
  setFeatured: inv("featured:set"),
  appVersion: () => ipcRenderer.invoke("app:version"),
  modify: inv("admin:modify"),
  deleteVersion: inv("admin:deleteVersion"),
  deleteInstance: inv("admin:deleteInstance"),
  hasToken: inv("admin:hasToken"),
  setToken: inv("admin:setToken"),
  pick: inv("admin:pick"),
  check: inv("admin:check"),
  loaders: inv("loaders:list"),
  publish: inv("admin:publish"),
  pathFor: (file) => webUtils.getPathForFile(file),
  onStatus: on("status"),
  onGameLog: on("game-log"),
  onAdminStatus: on("admin-status"),
});
